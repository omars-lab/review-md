#!/usr/bin/env node
/**
 * Generate the x-callback URL API docs from the single source of truth
 * (src/protocol/xcallback.schema.json), which the plugin also validates against
 * at runtime. Outputs into docs/api/:
 *   - xcallback.openapi.json  (OpenAPI 3.1 — load in any Swagger/OpenAPI tool)
 *   - index.html              (Swagger UI, loads the JSON above)
 *   - xcallback.md            (human-readable tables + example URLs)
 *
 * Usage:
 *   node scripts/gen-xcallback-api.mjs          # write the files
 *   node scripts/gen-xcallback-api.mjs --check  # fail (exit 1) if any file is stale
 *
 * `make api-docs` writes; `make api-check` / the pre-commit hook run --check, so
 * the docs can never drift from the schema (local == CI parity, per CLAUDE.md).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, join } from "node:path";

const repo = resolve(import.meta.dirname, "..");
const schemaPath = join(repo, "src", "protocol", "xcallback.schema.json");
const outDir = join(repo, "docs", "api");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
/** The URL a given operation is invoked at, e.g. obsidian://review-md-open */
const opUrl = (op) => `${schema.scheme}://${op.action}`;

const GEN_NOTE =
  "GENERATED by scripts/gen-xcallback-api.mjs from src/protocol/xcallback.schema.json — do not edit by hand. Run `make api-docs`.";

/** Build the example `obsidian://review-md-<op>?...` URL for an operation from its param examples. */
function exampleUrl(op) {
  const parts = [];
  for (const p of op.params) {
    if (p.required && p.example !== undefined) {
      parts.push(`${p.name}=${encodeURIComponent(p.example)}`);
    }
  }
  return `${opUrl(op)}?${parts.join("&")}`;
}

function buildOpenApi() {
  const spec = {
    openapi: "3.1.0",
    info: {
      title: schema.name,
      version: schema.version,
      description:
        `${schema.description}\n\n` +
        "**Not an HTTP API.** These are Obsidian custom-scheme URLs; each \"path\" below is an " +
        "Obsidian action (`obsidian://<action>`) and every parameter is passed in the query " +
        "string. Invoke a URL by opening it (e.g. `open '<url>'` on macOS, or `xdg-open` on " +
        "Linux). Note: Obsidian reserves `vault` (used to route to the vault window) — it is " +
        "required in the URL but is not delivered to the plugin.",
    },
    servers: [{ url: `${schema.scheme}://`, description: "Obsidian custom URL scheme." }],
    paths: {},
  };
  for (const op of schema.operations) {
    spec.paths[`/${op.action}`] = {
      get: {
        operationId: op.id,
        summary: op.summary,
        description: `${op.description}\n\nInvoke as: \`${opUrl(op)}?…\`\n\nExample: \`${exampleUrl(op)}\``,
        parameters: op.params.map((p) => ({
          name: p.name,
          in: "query",
          required: !!p.required,
          description: p.description,
          schema: {
            type: p.type,
            ...(p.enum ? { enum: p.enum } : {}),
            ...(p.default !== undefined ? { default: p.default } : {}),
          },
          ...(p.example !== undefined ? { example: p.example } : {}),
        })),
        responses: {
          "200": { description: "Success. If `x-success` was supplied, that URL is opened." },
          "400": {
            description: "Missing or invalid parameters. If `x-error` was supplied, that URL is opened.",
          },
        },
      },
    };
  }
  return spec;
}

function buildHtml() {
  return `<!doctype html>
<!-- ${GEN_NOTE} -->
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${schema.name}</title>
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui.css" />
  <style>body{margin:0}</style>
</head>
<body>
  <div id="swagger-ui"></div>
  <script src="https://cdn.jsdelivr.net/npm/swagger-ui-dist@5/swagger-ui-bundle.js" crossorigin></script>
  <script>
    window.ui = SwaggerUIBundle({
      url: "./xcallback.openapi.json",
      dom_id: "#swagger-ui",
      deepLinking: true,
      tryItOutEnabled: false,
    });
  </script>
</body>
</html>
`;
}

function buildMarkdown() {
  const lines = [];
  lines.push(`<!-- ${GEN_NOTE} -->`);
  lines.push("");
  lines.push(`# ${schema.name}`);
  lines.push("");
  lines.push(schema.description);
  lines.push("");
  lines.push(
    `- **Scheme:** \`${schema.scheme}://\`  ·  **Version:** ${schema.version}`,
  );
  lines.push(
    "- **Interactive spec:** open `docs/api/index.html` (Swagger UI) or load `docs/api/xcallback.openapi.json` in any OpenAPI tool.",
  );
  lines.push(
    "- **Invoke a URL:** `open '<url>'` (macOS) / `xdg-open '<url>'` (Linux), or click a generated link.",
  );
  lines.push(
    "- **Reserved params:** Obsidian consumes `vault` to route to the vault window (required in the URL, not passed to the plugin). Never name a param `action` or `vault`.",
  );
  lines.push("");
  for (const op of schema.operations) {
    lines.push(`## \`${opUrl(op)}\` — ${op.summary}`);
    lines.push("");
    lines.push(op.description);
    lines.push("");
    lines.push("| Param | Required | Type | Default / Enum | Description |");
    lines.push("|---|---|---|---|---|");
    for (const p of op.params) {
      const constraint = p.enum
        ? "enum: " + p.enum.map((e) => `\`${e}\``).join(", ")
        : p.default !== undefined
          ? `\`${p.default}\``
          : "—";
      const required = p.required ? (p.reserved ? "yes — URL only" : "yes") : "no";
      lines.push(
        `| \`${p.name}\` | ${required} | ${p.type} | ${constraint} | ${p.description} |`,
      );
    }
    lines.push("");
    lines.push("Example:");
    lines.push("");
    lines.push("```");
    lines.push(exampleUrl(op));
    lines.push("```");
    lines.push("");
  }
  return lines.join("\n");
}

const files = {
  "xcallback.openapi.json": JSON.stringify(buildOpenApi(), null, 2) + "\n",
  "index.html": buildHtml(),
  "xcallback.md": buildMarkdown(),
};

const check = process.argv.includes("--check");
let drift = false;
mkdirSync(outDir, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  const path = join(outDir, name);
  if (check) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      /* missing */
    }
    if (current !== content) {
      drift = true;
      console.error(`✗ docs/api/${name} is out of date`);
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote docs/api/${name}`);
  }
}

if (check) {
  if (drift) {
    console.error("\nx-callback API docs are stale — run `make api-docs` and commit the result.");
    process.exit(1);
  }
  console.log("x-callback API docs are in sync with the schema ✓");
} else {
  console.log("done — open docs/api/index.html to browse the API.");
}
